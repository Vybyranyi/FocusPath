export interface SeedReport {
    created: number;
    skipped: number;
    rejected: number;
}

/**
 * Creates any official plan that is not already there, and leaves the rest
 * alone — so an interrupted run can simply be repeated.
 *
 * Each seed becomes a real habit on the official account first, because a plan
 * is a snapshot *of a habit*: giving them a source keeps one path through the
 * code instead of a second one that exists only for seeding.
 *
 * Expects an open connection; the CLI below owns connecting.
 */
export const seedOfficialPlans = async (authorId: mongoose.Types.ObjectId): Promise<SeedReport> => {
    const report: SeedReport = { created: 0, skipped: 0, rejected: 0 };

    for (const seed of SEEDS) {
        const existing = await Plan.findOne({ title: seed.title, official: true });
        if (existing) {
            report.skipped += 1;
            continue;
        }

        const generated = await generateHabitPlan(seed.title, seed.type, seed.duration);
        const dayTitles = Array.from(
            { length: seed.duration },
            (_unused, index) => generated.dailyTasks[index]?.dayTitle ?? seed.title,
        );

        const review = await reviewPlan({
            title: seed.title,
            description: seed.description,
            dayTitles,
        });

        if (review.verdict === 'reject') {
            logger.warn({ title: seed.title, reason: review.reason }, 'Seed plan rejected by moderation');
            report.rejected += 1;
            continue;
        }

        const startDate = startOfUtcDay(new Date());
        const habit = await Habit.create({
            title: seed.title,
            description: seed.description,
            category: seed.category,
            startDate,
            type: seed.type,
            color: seed.color,
            icon: seed.icon,
            userId: authorId,
            rules: [{ effectiveFrom: startDate, frequency: { kind: 'daily' } }],
            program: dayTitles.map(title => ({ title })),
        });

        const plan = await Plan.create({
            title: seed.title,
            description: seed.description,
            category: seed.category,
            language: review.language,
            type: seed.type,
            duration: seed.duration,
            color: seed.color,
            icon: seed.icon,
            days: dayTitles.map(dayTitle => ({ dayTitle })),
            author: { userId: authorId },
            sourceHabitId: habit._id,
            contentHash: contentHash({ frequency: { kind: 'daily' } }, dayTitles),
            official: true,
            moderation: {
                checkedAt: new Date(),
                model: MODERATION_MODEL,
                verdict: review.verdict,
                reason: review.reason,
            },
        });

        habit.publishedPlanId = plan._id as mongoose.Types.ObjectId;
        await habit.save();

        report.created += 1;
        logger.info({ title: seed.title, language: review.language }, 'Seeded official plan');
    }

    return report;
};

const run = async () => {
    dotenv.config({ path: path.resolve(__dirname, '../../../.env') });

    const email = process.env.ADMIN_EMAIL;
    if (!email) {
        logger.error('ADMIN_EMAIL must be set in .env — official plans are published under that account');
        process.exit(1);
    }

    await connectDB();

    const author = await User.findOne({ email });
    if (!author) {
        logger.error(`No account for ${email}. Run "npm run seed:admin" first.`);
        await mongoose.disconnect();
        process.exit(1);
    }

    const report = await seedOfficialPlans(author._id as mongoose.Types.ObjectId);
    logger.info(report, 'Official plan seeding complete');

    await mongoose.disconnect();
};

if (require.main === module) {
    run().catch(async (error) => {
        logger.fatal({ err: error }, 'Failed to seed official plans');
        await mongoose.disconnect().catch(() => undefined);
        process.exit(1);
    });
}
